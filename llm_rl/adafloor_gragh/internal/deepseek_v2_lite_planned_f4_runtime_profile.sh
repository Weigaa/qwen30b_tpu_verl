#!/usr/bin/env bash

# Planned floor4 retains its survivor topology and the associated runtime state.
# Start from the validated DeepSeek mode1 memory lifecycle, then replace every
# policy-dependent setting explicitly. Update the profile ID when values change.
DEEPSEEK_P_F4_PROFILE_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
# shellcheck disable=SC1091
source "$DEEPSEEK_P_F4_PROFILE_DIR/deepseek_v2_lite_natural_f4_runtime_profile.sh"
unset DEEPSEEK_P_F4_PROFILE_DIR

export DEEPSEEK_P_F4_RUNTIME_PROFILE_ID=deepseek-v2-lite-planned-f4-mode1-v2
export DEEPSEEK_P_F4_RUNTIME_PROFILE_FILES=internal/deepseek_v2_lite_natural_f4_runtime_profile.sh,internal/deepseek_v2_lite_planned_f4_runtime_profile.sh

export VLLM_ASCEND_SHRINK_AWARE_TARGET_POLICY=planned
export VLLM_ASCEND_ELASTIC_MIN_COMPUTE_GROUP_SIZE=4
export VLLM_ASCEND_SHRINK_AWARE_STAGES=8,4
export VLLM_ASCEND_SHRINK_AWARE_INTERMEDIATE_RANKS=8,9,10,11,12,13,14,15
export VLLM_ASCEND_SHRINK_AWARE_FINAL_RANKS=12,13,14,15

# Capacity probes create group handles, topology caches, static dispatcher
# state, and expert slots before vLLM measures the KV cache. Live dispatcher
# tensors remain transient and must still be covered by strict authorization.
export VLLM_ASCEND_MODE1_PARITY_FIXED_TOPOLOGY_REUSE=1
export VLLM_ASCEND_MODE1_PARITY_PRECREATE_PLANNED_FLOOR_GROUPS=1
export VLLM_ASCEND_MODE1_PARITY_CACHE_PLANNED_FLOOR_GROUPS=1
export VLLM_ASCEND_MODE1_PARITY_PRECREATE_COMM_CACHE=1
export VLLM_ASCEND_MODE1_PARITY_PRECREATE_DISPATCH_WARMUP=1
export VLLM_ASCEND_MODE1_PARITY_PRECREATE_DISPATCH_WARMUP_TOKENS=32
export VLLM_ASCEND_MODE1_COMM_CACHE_STATE_LOG=1
export VLLM_ASCEND_MODE1_PARITY_PREFILL_PLANNED_EXPERT_SLOTS=1
export VLLM_ASCEND_MODE1_PARITY_PREFILL_PLANNED_EXPERT_SLOTS_ON_RESIZE=1
export VLLM_ASCEND_MODE1_NATURAL_PRUNE_RUNTIME_ON_KV_RESIZE=0
export VLLM_ASCEND_MODE1_NATURAL_FORCE_DESTROY_FLOOR_GROUPS_ON_KV_RESIZE=0
export VLLM_ASCEND_MODE1_CPU_DP_METADATA_SYNC=1

# Zero is the initial candidate for resources present during physical sizing.
# Strict authorization may establish a nonzero transient-workspace reserve.
export DEEPSEEK_P_F4_HEADROOM_FLOOR4=${DEEPSEEK_P_F4_HEADROOM_FLOOR4:-0}
export DEEPSEEK_P_F4_HEADROOM_FLOOR8=${DEEPSEEK_P_F4_HEADROOM_FLOOR8:-0}
export DEEPSEEK_P_F4_HEADROOM_FLOOR16=${DEEPSEEK_P_F4_HEADROOM_FLOOR16:-0}
export VLLM_ASCEND_MODE1_PARITY_PLANNED_FLOOR_GROUP_KV_HEADROOM_TOKENS=$DEEPSEEK_P_F4_HEADROOM_FLOOR4
export VLLM_ASCEND_MODE1_PARITY_PLANNED_FLOOR_GROUP_KV_HEADROOM_TOKENS_FLOOR2=0
export VLLM_ASCEND_MODE1_PARITY_PLANNED_FLOOR_GROUP_KV_HEADROOM_TOKENS_FLOOR4=$DEEPSEEK_P_F4_HEADROOM_FLOOR4
export VLLM_ASCEND_MODE1_PARITY_PLANNED_FLOOR_GROUP_KV_HEADROOM_TOKENS_FLOOR8=$DEEPSEEK_P_F4_HEADROOM_FLOOR8
export VLLM_ASCEND_MODE1_PARITY_PLANNED_FLOOR_GROUP_KV_HEADROOM_TOKENS_FLOOR16=$DEEPSEEK_P_F4_HEADROOM_FLOOR16

# The zero default permits measurement-only probes. A calibration wrapper must
# provide a positive DeepSeek-specific value before it can emit candidate caps.
export DEEPSEEK_P_F4_TRAINING_MIN_FREE_MIB=${DEEPSEEK_P_F4_TRAINING_MIN_FREE_MIB:-0}
export DYNAMIC_REQUIRE_EXPLICIT_PLANNED_MEMORY_GUARD=1
export VLLM_ASCEND_MODE1_RELEASE_MOE_RUNTIME_BEFORE_TRAINING=1
export VLLM_ASCEND_MODE1_TRAINING_MEMORY_GUARD=1
export VLLM_ASCEND_MODE1_TRAINING_MEMORY_GUARD_STRICT=1
export VLLM_ASCEND_MODE1_TRAINING_MIN_FREE_MIB=$DEEPSEEK_P_F4_TRAINING_MIN_FREE_MIB
export VLLM_ASCEND_MODE1_TRAINING_MIN_FREE_MIB_FLOOR=$DEEPSEEK_P_F4_TRAINING_MIN_FREE_MIB
export VLLM_ASCEND_MODE1_OFFLOAD_LOADED_WEIGHTS_AFTER_FULL_RESTORE=1
export VLLM_ASCEND_MODE1_OFFLOAD_CANONICAL_LOADED_WEIGHTS_AFTER_FULL_RESTORE=0
export VLLM_ASCEND_MODE1_SYNC_AFTER_FULL_RESTORE_WEIGHT_OFFLOAD=1

export VLLM_ROLLOUT_EARLY_STOP_ENABLE=0
export VERL_SIDECAR_ENABLE=0
export VLLM_ASCEND_ENABLE_DRAFT_TRAIN=0
export SAVE_DRAFT_HIDDEN_ENABLE=0
