#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)

# Full-length dynamic natural-policy validation with floor2 enabled.
#
# This reuses the existing mode0 probe from the floor4 natural tailguard run for
# length history, so it only executes two mode1 epochs: epoch_001 and epoch_002.
# If DYNAMIC_INITIAL_RESUME_CKPT is not provided, epoch_001 starts from the base
# model and epoch_002 resumes from epoch_001.  The floor2 cap is the largest
# no-trim value verified by the threshold-controlled floor2 sweep.

BASELINE_EPOCH0="${DYNAMIC_INITIAL_BASELINE_DIR:-$SCRIPT_DIR/mode1_dynamic_length_aware_adaptive_floor4_natural_tailguard_full3/epoch_000_mode0_probe}"
DYNAMIC_DISABLE_TAIL_GUARD="${DYNAMIC_DISABLE_TAIL_GUARD:-0}"
DYNAMIC_SHORT_STEP_CAP_ENABLE="${DYNAMIC_SHORT_STEP_CAP_ENABLE:-1}"
DYNAMIC_EXPECT_NO_RESPONSE_CAPS="${DYNAMIC_EXPECT_NO_RESPONSE_CAPS:-0}"

if [[ ! -d "$BASELINE_EPOCH0/rollout_data" ]]; then
    echo "missing reusable epoch0 rollout data: $BASELINE_EPOCH0/rollout_data" >&2
    exit 2
fi

export VLLM_ASCEND_SHRINK_AWARE_TARGET_POLICY=natural
export VLLM_ASCEND_SHRINK_AWARE_STAGES="${VLLM_ASCEND_SHRINK_AWARE_STAGES:-8,4,2}"
export VLLM_ASCEND_ELASTIC_MIN_COMPUTE_GROUP_SIZE="${VLLM_ASCEND_ELASTIC_MIN_COMPUTE_GROUP_SIZE:-2}"
export MIN_ADAPTIVE_FLOOR="${MIN_ADAPTIVE_FLOOR:-2}"
export ACTIVE_PEAK_SAFETY_FACTOR="${ACTIVE_PEAK_SAFETY_FACTOR:-1.16}"
export VLLM_ASCEND_MODE1_PARITY_MAX_KV_TOKENS_FLOOR2="${VLLM_ASCEND_MODE1_PARITY_MAX_KV_TOKENS_FLOOR2:-131072}"
export VLLM_ASCEND_MODE1_PARITY_MAX_KV_TOKENS_FLOOR4="${VLLM_ASCEND_MODE1_PARITY_MAX_KV_TOKENS_FLOOR4:-280576}"
export VLLM_ASCEND_MODE1_PARITY_MAX_KV_TOKENS_FLOOR8="${VLLM_ASCEND_MODE1_PARITY_MAX_KV_TOKENS_FLOOR8:-315648}"
export VLLM_ASCEND_MODE1_PARITY_MAX_KV_TOKENS="${VLLM_ASCEND_MODE1_PARITY_MAX_KV_TOKENS:-380800}"
export VLLM_ASCEND_MODE1_RELOAD_TRIM_ALLOCATOR="${VLLM_ASCEND_MODE1_RELOAD_TRIM_ALLOCATOR:-0}"
export VLLM_ASCEND_MODE1_RELOAD_SYNC_ON_TRIM="${VLLM_ASCEND_MODE1_RELOAD_SYNC_ON_TRIM:-0}"
export VLLM_ASCEND_FULL_REDUNDANCY_EXPERIMENT_LOG="${VLLM_ASCEND_FULL_REDUNDANCY_EXPERIMENT_LOG:-0}"
export VLLM_ASCEND_MODE1_CPU_DP_METADATA_SYNC="${VLLM_ASCEND_MODE1_CPU_DP_METADATA_SYNC:-1}"
export VLLM_ASCEND_MODE1_REFRESH_GROUPS_ON_KV_RESIZE="${VLLM_ASCEND_MODE1_REFRESH_GROUPS_ON_KV_RESIZE:-1}"
export VLLM_ASCEND_MODE1_FULLWORLD_REFRESH_MC2_WARMUP="${VLLM_ASCEND_MODE1_FULLWORLD_REFRESH_MC2_WARMUP:-1}"
export VLLM_ASCEND_MODE1_PARITY_POST_RESTORE_MC2_WARMUP="${VLLM_ASCEND_MODE1_PARITY_POST_RESTORE_MC2_WARMUP:-1}"
export VLLM_ASCEND_MODE1_PARITY_POST_RESTORE_MC2_WARMUP_TOKENS="${VLLM_ASCEND_MODE1_PARITY_POST_RESTORE_MC2_WARMUP_TOKENS:-32}"
export VLLM_ASCEND_MODE1_PARITY_MC2_WARMUP_ROUTE="${VLLM_ASCEND_MODE1_PARITY_MC2_WARMUP_ROUTE:-global}"
export VLLM_ASCEND_MODE1_KV_PREEMPT_DIAG="${VLLM_ASCEND_MODE1_KV_PREEMPT_DIAG:-0}"
export VLLM_ASCEND_MODE1_KV_PREEMPT_DIAG_LIMIT="${VLLM_ASCEND_MODE1_KV_PREEMPT_DIAG_LIMIT:-40}"
export VLLM_ASCEND_MODE1_FULLWORLD_RESTORE_DIAG="${VLLM_ASCEND_MODE1_FULLWORLD_RESTORE_DIAG:-0}"
export VLLM_ASCEND_MODE1_STEP_TIMELINE_LOG="${VLLM_ASCEND_MODE1_STEP_TIMELINE_LOG:-0}"
export VLLM_ASCEND_MODE1_PARITY_MC2_MEM_LOG="${VLLM_ASCEND_MODE1_PARITY_MC2_MEM_LOG:-0}"
export VLLM_ASCEND_MODE1_PARITY_MC2_MEM_LOG_ALL="${VLLM_ASCEND_MODE1_PARITY_MC2_MEM_LOG_ALL:-0}"
export VLLM_ASCEND_MODE1_CLEAR_STALE_PARAM_DICTS_AFTER_OLD_KV="${VLLM_ASCEND_MODE1_CLEAR_STALE_PARAM_DICTS_AFTER_OLD_KV:-1}"
export VLLM_ASCEND_MODE1_PRESERVE_KV_ON_SAME_FLOOR_NEXT_STEP=0
export VLLM_ASCEND_MODE1_STAGE_WEIGHTS_BEFORE_KV_REBUILD="${VLLM_ASCEND_MODE1_STAGE_WEIGHTS_BEFORE_KV_REBUILD:-1}"
export VLLM_ASCEND_MODE1_BOOTSTRAP_KV_BEFORE_WEIGHT_ONLOAD="${VLLM_ASCEND_MODE1_BOOTSTRAP_KV_BEFORE_WEIGHT_ONLOAD:-1}"
export VLLM_ASCEND_MODE1_BOOTSTRAP_KV_TOKENS="${VLLM_ASCEND_MODE1_BOOTSTRAP_KV_TOKENS:-${VLLM_ASCEND_MODE1_PARITY_MAX_KV_TOKENS_FLOOR2}}"
export VLLM_ASCEND_MODE1_COLD_INIT_KV_TOKENS="${VLLM_ASCEND_MODE1_COLD_INIT_KV_TOKENS:-2048}"
export VLLM_ASCEND_MODE1_USE_COLD_INIT_KV_CAP="${VLLM_ASCEND_MODE1_USE_COLD_INIT_KV_CAP:-1}"
export VLLM_ASCEND_MODE1_PROFILE_EXTRA_MC2_DUMMY="${VLLM_ASCEND_MODE1_PROFILE_EXTRA_MC2_DUMMY:-0}"
export VLLM_ASCEND_MODE1_PROFILE_MC2_DUMMY_TOKENS="${VLLM_ASCEND_MODE1_PROFILE_MC2_DUMMY_TOKENS:-128}"
export VLLM_ASCEND_MODE1_PROFILE_MAX_TOKENS="${VLLM_ASCEND_MODE1_PROFILE_MAX_TOKENS:-2048}"
export VLLM_ASCEND_MODE1_PROFILE_AVOID_MC2_BOUNDARY="${VLLM_ASCEND_MODE1_PROFILE_AVOID_MC2_BOUNDARY:-1}"
export VLLM_ASCEND_MODE1_PROFILE_MC2_AVOID_TOKENS="${VLLM_ASCEND_MODE1_PROFILE_MC2_AVOID_TOKENS:-640}"
export VLLM_ASCEND_MODE1_USE_EXPLICIT_KV_CAP_FOR_INIT="${VLLM_ASCEND_MODE1_USE_EXPLICIT_KV_CAP_FOR_INIT:-0}"
export FLOOR_KV_CAPS="${FLOOR_KV_CAPS:-2:${VLLM_ASCEND_MODE1_PARITY_MAX_KV_TOKENS_FLOOR2},4:${VLLM_ASCEND_MODE1_PARITY_MAX_KV_TOKENS_FLOOR4},8:${VLLM_ASCEND_MODE1_PARITY_MAX_KV_TOKENS_FLOOR8},16:${VLLM_ASCEND_MODE1_PARITY_MAX_KV_TOKENS}}"

# Upward transitions such as floor2->floor4 release old KV before floor prepare,
# then compact MoE state.  Avoid repeated allocator trims inside that compact
# loop; the later resize memory query still performs one trim/sync before
# allocating the new KV cache.
export VLLM_ASCEND_MODE1_CLEAR_OLD_KV_BEFORE_UPWARD_FLOOR_PREPARE="${VLLM_ASCEND_MODE1_CLEAR_OLD_KV_BEFORE_UPWARD_FLOOR_PREPARE:-1}"
