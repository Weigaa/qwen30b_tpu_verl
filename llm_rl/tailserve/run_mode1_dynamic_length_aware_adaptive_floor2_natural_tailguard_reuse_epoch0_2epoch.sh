echo "[dynamic floor2 natural] disable_tail_guard=$DYNAMIC_DISABLE_TAIL_GUARD short_step_cap_enable=$DYNAMIC_SHORT_STEP_CAP_ENABLE expect_no_response_caps=$DYNAMIC_EXPECT_NO_RESPONSE_CAPS"

DYNAMIC_RUN_NAME="${DYNAMIC_RUN_NAME:-mode1_dynamic_length_aware_adaptive_floor2_natural_tailguard_reuse_epoch0_2epoch}" \
DYNAMIC_TOTAL_EPOCHS="${DYNAMIC_TOTAL_EPOCHS:-3}" \
