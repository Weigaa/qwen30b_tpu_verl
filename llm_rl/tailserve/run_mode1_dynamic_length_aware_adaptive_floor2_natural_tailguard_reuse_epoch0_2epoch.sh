export VLLM_ASCEND_MODE1_PARITY_PRECREATE_PLANNED_FLOOR_GROUPS=0
export VLLM_ASCEND_MODE1_PARITY_CACHE_PLANNED_FLOOR_GROUPS=0
export VLLM_ASCEND_MODE1_PARITY_PRECREATE_COMM_CACHE=0
export VLLM_ASCEND_MODE1_PARITY_PRECREATE_DISPATCH_WARMUP=0
export VLLM_ASCEND_MODE1_PARITY_CACHE_FLOOR_GROUPS=0
export VLLM_ASCEND_MODE1_PARITY_KEEP_MC2_GROUP_CACHE=0
export VLLM_ASCEND_MODE1_PARITY_KEEP_FLOOR4_GROUP_CACHE=0

# Lightweight corruption diagnostics.  These only dump layer shape/state and a
# few active-slot samples before generate; they avoid the heavier per-execute
# fingerprint logs unless explicitly enabled by the caller.
export VLLM_ASCEND_MODE1_EXECUTE_SHAPE_LOG="${VLLM_ASCEND_MODE1_EXECUTE_SHAPE_LOG:-0}"
export VLLM_ASCEND_MODE1_PRE_GENERATE_STATE_DUMP="${VLLM_ASCEND_MODE1_PRE_GENERATE_STATE_DUMP:-0}"
export VLLM_ASCEND_MODE1_PRE_GENERATE_STATE_LAYERS="${VLLM_ASCEND_MODE1_PRE_GENERATE_STATE_LAYERS:-0}"
export VLLM_ASCEND_MODE1_PRE_GENERATE_STATE_MAX_LAYERS="${VLLM_ASCEND_MODE1_PRE_GENERATE_STATE_MAX_LAYERS:-1}"
export VLLM_ASCEND_MODE1_PRE_GENERATE_STATE_EXPERTS="${VLLM_ASCEND_MODE1_PRE_GENERATE_STATE_EXPERTS:-8}"
export VLLM_ASCEND_MODE1_PRE_GENERATE_STATE_VALUES="${VLLM_ASCEND_MODE1_PRE_GENERATE_STATE_VALUES:-8}"
export VLLM_ASCEND_MODE1_PRE_GENERATE_STATE_STRICT="${VLLM_ASCEND_MODE1_PRE_GENERATE_STATE_STRICT:-1}"
export VLLM_ASCEND_MODE1_WEIGHT_FINGERPRINT_LOG="${VLLM_ASCEND_MODE1_WEIGHT_FINGERPRINT_LOG:-0}"
export VLLM_ASCEND_MODE1_PROCESS_WEIGHT_DIAG="${VLLM_ASCEND_MODE1_PROCESS_WEIGHT_DIAG:-0}"
export VLLM_ASCEND_MODE1_PROCESS_WEIGHT_DIAG_LAYERS="${VLLM_ASCEND_MODE1_PROCESS_WEIGHT_DIAG_LAYERS:-0}"
export VLLM_ASCEND_MODE1_PROCESS_WEIGHT_DIAG_VALUES="${VLLM_ASCEND_MODE1_PROCESS_WEIGHT_DIAG_VALUES:-8}"
export VLLM_ASCEND_MODE1_RELOAD_CHAIN_DIAG="${VLLM_ASCEND_MODE1_RELOAD_CHAIN_DIAG:-0}"
export VLLM_ASCEND_MODE1_RELOAD_CHAIN_DIAG_LAYERS="${VLLM_ASCEND_MODE1_RELOAD_CHAIN_DIAG_LAYERS:-0}"
export VLLM_ASCEND_MODE1_RELOAD_CHAIN_DIAG_VALUES="${VLLM_ASCEND_MODE1_RELOAD_CHAIN_DIAG_VALUES:-8}"
export VLLM_ASCEND_MODE1_DIAG_DURING_PROFILE="${VLLM_ASCEND_MODE1_DIAG_DURING_PROFILE:-0}"
export VLLM_ASCEND_MODE1_DIRECT_NPU_IMPORT_VERIFY_LOG="${VLLM_ASCEND_MODE1_DIRECT_NPU_IMPORT_VERIFY_LOG:-0}"
export VLLM_ASCEND_MODE1_DIRECT_NPU_IMPORT_VERIFY_VALUES="${VLLM_ASCEND_MODE1_DIRECT_NPU_IMPORT_VERIFY_VALUES:-8}"
export VLLM_ASCEND_MODE1_LOG2PHY_SYNC_LOG="${VLLM_ASCEND_MODE1_LOG2PHY_SYNC_LOG:-0}"
export VLLM_ASCEND_MODE1_VALIDATE_EXPERT_MAPPING="${VLLM_ASCEND_MODE1_VALIDATE_EXPERT_MAPPING:-0}"
