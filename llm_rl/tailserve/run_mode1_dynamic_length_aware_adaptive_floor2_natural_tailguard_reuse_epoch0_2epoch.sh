echo "[dynamic floor2 natural] execute_shape_log=$VLLM_ASCEND_MODE1_EXECUTE_SHAPE_LOG pre_generate_state_dump=$VLLM_ASCEND_MODE1_PRE_GENERATE_STATE_DUMP layers=$VLLM_ASCEND_MODE1_PRE_GENERATE_STATE_LAYERS experts=$VLLM_ASCEND_MODE1_PRE_GENERATE_STATE_EXPERTS values=$VLLM_ASCEND_MODE1_PRE_GENERATE_STATE_VALUES"
