export VLLM_ASCEND_MODE1_WEIGHT_RELOAD_CAPACITY_LOG="${VLLM_ASCEND_MODE1_WEIGHT_RELOAD_CAPACITY_LOG:-0}"
export VLLM_ASCEND_MODE1_FULL_RESTORE_OFFLOAD_STORAGE_DIAG="${VLLM_ASCEND_MODE1_FULL_RESTORE_OFFLOAD_STORAGE_DIAG:-0}"
export VLLM_ASCEND_CUSTOM_MODE1_KV_DIAG="${VLLM_ASCEND_CUSTOM_MODE1_KV_DIAG:-0}"
export VLLM_ASCEND_MODE1_KV_ALLOC_TRACE="${VLLM_ASCEND_MODE1_KV_ALLOC_TRACE:-0}"
export VLLM_ASCEND_MODE1_ENGINE_KV_INIT_DIAG="${VLLM_ASCEND_MODE1_ENGINE_KV_INIT_DIAG:-0}"

echo "[dynamic floor2 natural] reusable_epoch0=$BASELINE_EPOCH0"
echo "[dynamic floor2 natural] initial_resume_ckpt=${DYNAMIC_INITIAL_RESUME_CKPT:-<none>}"
echo "[dynamic floor2 natural] stages=$VLLM_ASCEND_SHRINK_AWARE_STAGES min_floor=$MIN_ADAPTIVE_FLOOR active_peak_safety_factor=$ACTIVE_PEAK_SAFETY_FACTOR floor_caps=$FLOOR_KV_CAPS"
echo "[dynamic floor2 natural] preserve_same_floor_kv=$VLLM_ASCEND_MODE1_PRESERVE_KV_ON_SAME_FLOOR_NEXT_STEP"
echo "[dynamic floor2 natural] stage_weights_before_kv_rebuild=$VLLM_ASCEND_MODE1_STAGE_WEIGHTS_BEFORE_KV_REBUILD"
echo "[dynamic floor2 natural] bootstrap_kv_before_weight_onload=$VLLM_ASCEND_MODE1_BOOTSTRAP_KV_BEFORE_WEIGHT_ONLOAD bootstrap_kv_tokens=$VLLM_ASCEND_MODE1_BOOTSTRAP_KV_TOKENS"
echo "[dynamic floor2 natural] cold_init_kv_tokens=$VLLM_ASCEND_MODE1_COLD_INIT_KV_TOKENS use_cold_init_kv_cap=$VLLM_ASCEND_MODE1_USE_COLD_INIT_KV_CAP"
echo "[dynamic floor2 natural] profile_max_tokens=$VLLM_ASCEND_MODE1_PROFILE_MAX_TOKENS avoid_mc2_boundary=$VLLM_ASCEND_MODE1_PROFILE_AVOID_MC2_BOUNDARY avoid_tokens=$VLLM_ASCEND_MODE1_PROFILE_MC2_AVOID_TOKENS extra_mc2_profile=$VLLM_ASCEND_MODE1_PROFILE_EXTRA_MC2_DUMMY mc2_profile_tokens=$VLLM_ASCEND_MODE1_PROFILE_MC2_DUMMY_TOKENS explicit_kv_cap_for_init=$VLLM_ASCEND_MODE1_USE_EXPLICIT_KV_CAP_FOR_INIT"
echo "[dynamic floor2 natural] memory_profile_log=$VLLM_ASCEND_FULL_REDUNDANCY_EXPERIMENT_LOG"
