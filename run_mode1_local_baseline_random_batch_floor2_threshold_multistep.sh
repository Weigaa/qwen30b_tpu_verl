export VLLM_ASCEND_MODE1_PARITY_DROP_FULLWORLD_GROUP_CACHE_AFTER_SHRINK="${VLLM_ASCEND_MODE1_PARITY_DROP_FULLWORLD_GROUP_CACHE_AFTER_SHRINK:-1}"
export VLLM_ASCEND_MODE1_PARITY_FORCE_CLEANUP_AFTER_FULLWORLD_GROUP_RELEASE="${VLLM_ASCEND_MODE1_PARITY_FORCE_CLEANUP_AFTER_FULLWORLD_GROUP_RELEASE:-1}"
export VLLM_ASCEND_MODE1_PARITY_KEEP_FULLWORLD_EP_CACHE="${VLLM_ASCEND_MODE1_PARITY_KEEP_FULLWORLD_EP_CACHE:-0}"
