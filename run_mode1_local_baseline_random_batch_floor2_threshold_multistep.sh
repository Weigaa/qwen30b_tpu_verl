export VLLM_ASCEND_MODE1_PARITY_FORCE_DESTROY_PLANNED_PRUNE="${VLLM_ASCEND_MODE1_PARITY_FORCE_DESTROY_PLANNED_PRUNE:-1}"
if [[ "${MODE1_FLOOR2_SUCCESS_LOGIC}" =~ ^(1|true|TRUE|yes|YES|on|ON)$ ]]; then
    export VLLM_ASCEND_FORCE_MC2_MOE="${VLLM_ASCEND_FORCE_MC2_MOE:-1}"
