    "${VLLM_ASCEND_FORCE_MC2_MOE:-<unset>}" \
    "${VLLM_ASCEND_FORCE_ALLTOALL_MOE:-<unset>}" \
    "${VLLM_ASCEND_AVOID_ALLTOALL_ON_SHRINK_STAGE:-<unset>}" \
    "${VLLM_ASCEND_RESERVED_MC2_MASK_TOKENS:-<unset>}" \
