export VLLM_ASCEND_MODE1_RELEASE_MOE_COMM_RUNTIME_EMPTY_CACHE="${VLLM_ASCEND_MODE1_RELEASE_MOE_COMM_RUNTIME_EMPTY_CACHE:-1}"
export VLLM_ASCEND_MODE1_SYNC_BEFORE_MOE_COMM_RELEASE="${VLLM_ASCEND_MODE1_SYNC_BEFORE_MOE_COMM_RELEASE:-1}"
export VLLM_ASCEND_MODE1_RESTORE_TAIL_NPU_SYNC="${VLLM_ASCEND_MODE1_RESTORE_TAIL_NPU_SYNC:-1}"
export VLLM_ASCEND_MODE1_RESTORE_TAIL_CPU_BARRIER="${VLLM_ASCEND_MODE1_RESTORE_TAIL_CPU_BARRIER:-1}"
export VLLM_ASCEND_MODE1_SHRINK_TAIL_NPU_SYNC="${VLLM_ASCEND_MODE1_SHRINK_TAIL_NPU_SYNC:-1}"
